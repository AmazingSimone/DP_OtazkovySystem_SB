const mongoose = require("mongoose")

const QuestionSchema = new mongoose.Schema(
    {
        text: {
            type: String,
            required: true,
            trim: true,
        },
        options: {
            a: { type: String, required: true, trim: true },
            b: { type: String, required: true, trim: true },
            c: { type: String, required: true, trim: true },
            d: { type: String, required: true, trim: true },
        },
        correct: {
            type: String,
            enum: ["a", "b", "c", "d"],
            required: true,
        },
        modul: {
            type: mongoose.Schema.Types.ObjectId,
            ref: "Module",
            required: true,
        },
        createdBy: {
            type: mongoose.Schema.Types.ObjectId,
            ref: "User",
            required: true,
        },
        createdByName: {
            type: String,
            default: null,
        },
        validated: { type: Boolean, default: false },
        validated_by: {
            type: mongoose.Schema.Types.ObjectId,
            ref: "Teacher",
        },
        validated_at: { type: Date },
        validation_comment: { type: String, trim: true },
        // Set when the review was generated by the system instead of a student:
        //   missing_reviewer     - no reviewer could be assigned at the start of week 2
        //   reviewer_no_response - a reviewer was assigned but did not review during week 2
        review_tag: {
            type: String,
            enum: ["missing_reviewer", "reviewer_no_response", null],
            default: null,
        },

        // Week 3: the author publishes the question, which sends it to the teacher
        published: { type: Boolean, default: false },
        published_at: { type: Date },
        // Snapshot of { text, options, correct } taken before the author's first week 3 edit
        original: { type: mongoose.Schema.Types.Mixed, default: null },

        // Teacher validation (additional validation by teachers)
        validated_by_teacher: { type: Boolean, default: false },
        validated_by_teacher_at: { type: Date },
        validated_by_teacher_comment: { type: String, trim: true },
        // Final decision on a published question. validated_by_teacher mirrors "approved",
        // which is what the test pool selects on.
        teacher_status: {
            type: String,
            enum: ["pending", "approved", "rejected", "abuse"],
            default: "pending",
        },
        teacher_reviewed_by: {
            type: mongoose.Schema.Types.ObjectId,
            ref: "Teacher",
        },

        // User's response to validation
        user_agreement: {
            agreed: { type: Boolean },
            comment: { type: String, trim: true },
            responded_at: { type: Date },
        },

        // Rating statistics (cached for performance)
        rating_stats: {
            average_rating: { type: Number, default: 0 },
            total_ratings: { type: Number, default: 0 },
        },

        // Track points awarded for this question
        pointsAwarded: {
            creation: { type: Boolean, default: false }, // Week 1 - Creation
            validation: { type: Boolean, default: false }, // Week 2 - Validation
            reparation: { type: Boolean, default: false }, // Week 3 - Reparation
        },

        is_active: { type: Boolean, default: true },
    },
    {
        timestamps: true,
        toJSON: { virtuals: true },
        toObject: { virtuals: true },
    },
)

// Indexes
QuestionSchema.index({ modul: 1, createdBy: 1 })
QuestionSchema.index({ validated: 1, modul: 1 })
QuestionSchema.index({ createdBy: 1, createdAt: -1 })
QuestionSchema.index({ "rating_stats.average_rating": -1 })

// Compound index for weekly question tracking
QuestionSchema.index({
    createdBy: 1,
    modul: 1,
    created_at: -1,
})

module.exports = mongoose.model("Question", QuestionSchema)
